//================================================================================================
// Module Name : top_ahb
// Project     : AHB Lite Master
// Author      : Ansh Shinde
//
// Description :
//
// Top-level module of the AHB Lite master. It integrates the
// AHB datapath (data_ahb) and control path (control_ahb).
//
// The control path generates the required control signals based
// on incoming requests and AHB response signals. The datapath
// performs address generation, burst management, and data handling.
//
// Features:
// - Integration of AHB control and datapath modules
// - Single and burst transfer support
// - AHB address and data phase control
// - Address generation and burst management
// - Transfer size validation
// - Write data handling
// - Read data capture
// - AHB ready and response handling
// - Read data availability indication
// - Slave selection output (HSELB)
//
// Interface:
// - Receives transaction requests from the external interface.
// - Interfaces with the AHB slave through address, control,
//   write-data, read-data, ready, and response signals.
// - Provides transaction status and read data to the requester.
//
// Notes:
// - data_ahb handles address generation, transfer size checking,
//   burst counters, and read/write data operations.
// - control_ahb implements the FSM and generates datapath control signals.
// - Both modules communicate through internal control and status signals.
// - HSELB is generated by the control path and provided as an output.
// - The top-level module connects the internal blocks without
//   implementing additional transaction logic.
//
//================================================================================================
module top_ahb(
    input        clk,
    input        reset,
    input        req_valid,
    input        last_beat,
    input        req_write,
    input  [31:0]req_addr,
    input  [1:0] req_size,
    input  [2:0] req_burst,
    input  [31:0]wdata,
    input  [31:0]hrdata,
    input        hready,
    input        hresp,
    output [31:0]resp_rdata,
    output       hwrite,
    output       nxt_beat,
    output       rd_available,
    output       resp_error,
    output       ready,
    output       hselb,
    output [1:0] htrans,      
    output [31:0]haddr,
    output [1:0] hsize,
    output [2:0] hburst,
    output [31:0]hwdata
);

    wire init,
         clr,
         cont,
         check_size,
         gen_addr,
         sel_lane,
         valid_size;

     wire [4:0]data_count,addr_count,burst_beats;

     data_ahb ahb_dat(
       .hclk(clk),
       .hreset(reset),
       .init(init),
       .cont(cont),
       .req_valid(req_valid),
       .clr(clr),
       .check_size(check_size),
       .gen_addr(gen_addr),
       .sel_lane(sel_lane),
       .req_write(req_write),
       .req_addr(req_addr),
       .req_size(req_size),
       .req_burst(req_burst),
       .wdata(wdata),
       .hrdata(hrdata),
       .valid_size(valid_size),
       .data_count(data_count),
       .addr_count(addr_count),
       .resp_rdata(resp_rdata),
       .hwrite(hwrite),
       .burst_beats(burst_beats), 
       .haddr(haddr),
       .hsize(hsize),
       .hburst(hburst),
       .hwdata(hwdata)
     );

     control_ahb ahb_ctrl(
        .hclk(clk),
        .hreset(reset),
        .hready(hready),
        .hresp(hresp),
        .req_valid(req_valid),
        .req_write(req_write),
        .req_burst(req_burst),
        .last_beat(last_beat),
        .valid_size(valid_size),
        .data_count(data_count),
        .addr_count(addr_count),
        .burst_beats(burst_beats),
        .init(init),
        .cont(cont),
        .clr(clr),
        .check_size(check_size),
        .gen_addr(gen_addr),
        .sel_lane(sel_lane),
        .htrans(htrans),
        .ready(ready), 
        .nxt_beat(nxt_beat), 
        .rd_available(rd_available),
        .hselb(hselb),
        .resp_error(resp_error)
     );

endmodule
